    check("camera-collision speed gate 50 mph", e.rf(0x003F721C), 50.0, 1e-6)
    check("FUN_00011900 takes DEGREES (deg2rad at 0x0001190C)",
          e.rf(0x003A1248), 0.01745329238474369, 1e-9)

