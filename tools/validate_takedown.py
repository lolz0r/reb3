    import math

    def car_rows(pitch, yaw, roll, pos):
        p, y, r = (math.radians(v) for v in (pitch, yaw, roll))
        rx = [[1, 0, 0], [0, math.cos(p), math.sin(p)],
              [0, -math.sin(p), math.cos(p)]]
        ry = [[math.cos(y), 0, -math.sin(y)], [0, 1, 0],
              [math.sin(y), 0, math.cos(y)]]
        rz = [[math.cos(r), math.sin(r), 0], [-math.sin(r), math.cos(r), 0],
              [0, 0, 1]]
        def mul(a, b):
            return [[sum(a[i][k] * b[k][j] for k in range(3))
                     for j in range(3)] for i in range(3)]
        m = mul(mul(rz, rx), ry)
        return [m[0], m[1], m[2], list(pos)]

    # a seeded tumbling wreck: launch, spin, land.  Each scenario is run
