def _text_bytes():
    """(vaddr, bytes) of the .text-bearing load segments of the ELF."""
    path = os.path.join(_root, "build", "burnout3.elf")
    b = open(path, 'rb').read()
    phoff, = struct.unpack_from('<I', b, 0x1C)
    phentsize, phnum = struct.unpack_from('<HH', b, 0x2A)
    segs = []
    for i in range(phnum):
        o = phoff + i * phentsize
        t, off, va, _pa, fsz, _msz = struct.unpack_from('<6I', b, o)
        if t == 1 and 0x00011000 <= va < 0x00360000:
            segs.append((va, b[off:off + fsz]))
    return segs


def _count_refs_to_shake_cfg(segs):
    """Every instruction in .text that can produce DAT_0047A134 + 0x2C30.

    The camera-shake ValueDB block (11 groups x 0x30, group 0 =
    Crash/HandyCam) lives at manager+0x2C30.  If the springs were consumed
    anywhere, some instruction would have to address into the block off a
    base register -- a `[reg + disp]` memory operand, an `lea reg,[reg+disp]`
    or an `add reg, imm` -- with disp/imm inside it.  This counts exactly
    those three forms (bare immediates that merely happen to fall in the
    range, e.g. `push 0x2d80`, are not addressings and are excluded).

    Retail has exactly two hits: the constructor LEA at 0x00167273 that
    hands the block to the registrar FUN_00160B90, and the destructor ADD
    at 0x001AAA64 that hands it to the unregistrar FUN_00161990.  Nothing
    in between ever reads a spring, a damping or a Safe FOV out of it.
    """
    import re
    from capstone import Cs, CS_ARCH_X86, CS_MODE_32
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    lo, hi = 0x2C30, 0x2C30 + 11 * 0x30
    mem = re.compile(r'\[e[a-z]{2}(?:\s*\+\s*e[a-z]{2}(?:\*\d+)?)?'
                     r'\s*\+\s*(0x[0-9a-f]+)\]')
    addi = re.compile(r'^e[a-z]{2},\s*(0x[0-9a-f]+)$')
    hits = []
    for va, code in segs:
        pos = 0
        while pos < len(code):
            n = 0
            for ins in md.disasm(code[pos:], va + pos):
                n = ins.address - (va + pos) + ins.size
                cand = list(mem.findall(ins.op_str))
                if ins.mnemonic == 'add':
                    cand += addi.findall(ins.op_str)
                for tok in cand:
                    if lo <= int(tok, 16) < hi:
                        hits.append((ins.address, ins.mnemonic, ins.op_str))
                        break
            if n == 0:
                pos += 1
            else:
                pos += n
    return hits



