def section_timer():
    print("\n[1] time dilation -- FUN_001B5AC0 / FUN_001B5B60 executed")
    sched = [1, 1, 1, 5, 5, 5, 5, 5, 1, 1, 1, 6, 6, 3, 3, 4, 4, 1]
    real = tdfx.run_timer(sched)
    c = drive("timer", 1.0 / 60.0, *sched)
    check("timer: frame count", len(c), len(real))
    for i, ln in enumerate(c):
        f, div, dt, clock = ln.split()
        check("timer f%02d divisor" % i, int(div), real[i]['div'])
        check("timer f%02d dt" % i, float(dt), real[i]['dt'], 1e-9)
        check("timer f%02d clock" % i, float(clock), real[i]['clock'], 1e-6)

    # the divisor really is a 1/N timescale: 5 frames at divisor 5 advance
    # the clock by exactly one normal frame
    dilated = real[7]['clock'] - real[2]['clock']
    check("5 dilated frames == 1 normal frame", round(dilated, 7),
          round(real[2]['clock'] - real[1]['clock'], 7), 1e-6)

    for cur, req, whole, rem in ((1, 5, 10, 0), (5, 1, 10, 3), (5, 1, 10, 2),
                                 (5, 3, 7, 4), (3, 6, 100, 2), (6, 1, 4, 4)):
        r = tdfx.run_rescale(cur, req, whole, rem)
        out = drive("rescale", 1.0 / 60.0, cur, req, whole, rem)[0].split()
        tag = "rescale %d->%d rem%d" % (cur, req, rem)
        check(tag + " divisor", int(out[0]), r['div'])
        check(tag + " dt", float(out[1]), r['dt'], 1e-9)
        check(tag + " whole", int(out[2]), r['whole'])
        check(tag + " rem", int(out[3]), r['rem'])


