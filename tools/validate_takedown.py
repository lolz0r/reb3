def parse_update(lines):
    out = []
    for ln in lines:
        head, _, p = ln.partition("posts=")
        f = head.split()
        ev = [tuple(int(x) for x in q.split(':')[:2])
              for q in p.split(',') if q and q.split(':')[0] != '-1']
        st = [int(q.split(':')[2]) for q in p.split(',')
              if q and q.split(':')[2] != '-1']
        out.append(dict(i=int(f[0]), t=float(f[1]), active=int(f[2]),
                        callout_done=int(f[3]), flag_c=int(f[4]),
                        div_req=int(f[5]), cam_on=int(f[6]),
                        hud_flag=int(f[7]), burnout_grant=int(f[8]),
                        pv_auth=float(f[9]), pv_drift=int(f[10]),
                        pv_flags=int(f[11]), hud_events=ev, states=st))
    return out


