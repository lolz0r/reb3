DRIVER_SRC = os.path.join(_root, "build", "tdfx_driver.c")
DRIVER_BIN = os.path.join(_root, "build", "tdfx_driver")


def build_driver():
    os.makedirs(os.path.join(_root, "build"), exist_ok=True)
    with open(DRIVER_SRC, 'w') as f:
        f.write(DRIVER_C)
    cmd = ["gcc", "-Wall", "-Wextra", "-std=c11", "-O2",
           "-I" + os.path.join(_root, "src"), "-o", DRIVER_BIN, DRIVER_SRC,
           os.path.join(_root, "src", "burnout3_takedown.c"), "-lm"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout)
        print(r.stderr)
        raise SystemExit("driver build failed")
    if r.stderr.strip():
        print("  (driver build warnings)\n" + r.stderr)


def drive(*args):
    r = subprocess.run([DRIVER_BIN] + [str(a) for a in args],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit("driver failed: %s\n%s" % (args, r.stderr))
    return [ln for ln in r.stdout.splitlines() if ln.strip()]


