def section_gate_dedup():
    # run the real function with record+0x00 already == the victim
    e = tdfx.Emu()
    tdfx.seed_common(e)
    a = tdfx.seed_racecar(e, 0, cls=0)
    v = tdfx.seed_racecar(e, 1, cls=1, crashed=1)
    e.wf(v + 0x10DC, 1.0)
    e.wf(v + 0x140C, 0.5)
    e.wi(a + 0x15A4, v)
    tdfx.seed_record(e, slot=0, victim=v, active=0)
    from unicorn.x86_const import UC_X86_REG_EDX
    real = e.call(tdfx.F_GATE, regs={UC_X86_REG_EDX: tdfx.CAMREC}) & 0xFF
    got = int(drive("gate", 1, 1, 0, 0, 1, 1.0, 0.5)[0])
    check("gate: same victim as last time", got, real)


