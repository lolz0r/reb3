def globalus_string(blob, idx):
    off = struct.unpack_from('<I', blob, 0x10 + idx * 4)[0]
    end = off
    while end + 1 < len(blob) and blob[end:end + 2] != b'\0\0':
        end += 2
    return blob[off:end].decode('utf-16-le', 'replace')


