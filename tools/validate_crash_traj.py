def first_airborne_run(traj):
    """Index of the first frame after which the wreck stays airborne."""
    n = len(traj)
    i = n - 1
    while i > 0 and traj[i - 1]['airborne']:
        i -= 1
    return i


def traj_case(exe, label, scen, frames, window, row_budget):
    sim, speed, pre, traj = ect.SCENARIOS[scen](dt=DT, frames=frames)
    body = sim.export_body()
    start = first_airborne_run(traj)
    if start + window >= len(traj):
        window = len(traj) - start - 1
    seed = traj[start]
    st = {}
    rows = [seed['right'], seed['up'], seed['at'], seed['pos']]
    for r in range(4):
        for c in range(3):
            st['frame_%d_%d' % (r, c)] = rows[r][c]
        st['frame_%d_3' % r] = 1.0 if r == 3 else 0.0
    for i in range(3):
        st['vel_%d' % i] = seed['vel'][i]
        st['omega_%d' % i] = seed['omega'][i]
        st['angmom_%d' % i] = seed['angmom'][i]
        st['dir_%d' % i] = seed['dir'][i]
    st['vel_3'] = seed['speed']
    st['dir_3'] = seed['dir'][3]
    st['omega_3'] = 0.0
    st['angmom_3'] = 0.0
    for i in range(3):
        st['iinv_%d' % i] = body['iinv_%d' % i]
        for j in range(4):
            st['iw_%d_%d' % (i, j)] = seed['iinv_world'][i][j]
    st['mass'] = body['mass']
    st['com_height'] = body['com_height']
    st['dt'] = DT
    got = run_driver(exe, 'traj', st, extra=[window])

    worst_p = worst_v = worst_r = 0.0
    worst_L = 0.0
    for f in range(window):
        real = traj[start + 1 + f]
        g = got[f]
        worst_p = max(worst_p,
                      max(abs(g[i] - real['pos'][i]) for i in range(3)))
        worst_v = max(worst_v,
                      max(abs(g[12 + i] - real['vel'][i]) for i in range(3)))
        worst_r = max(worst_r,
                      max(max(abs(g[3 + i] - real['right'][i])
                              for i in range(3)),
                          max(abs(g[6 + i] - real['up'][i])
                              for i in range(3)),
                          max(abs(g[9 + i] - real['at'][i])
                              for i in range(3))))
        if f < 30:
            scale = max(1.0, max(abs(x) for x in real['angmom']))
            worst_L = max(worst_L,
                          max(abs(g[18 + i] - real['angmom'][i])
                              for i in range(3)) / scale)
    # first-step exactness pins the per-frame laws; the only thing left to
    # accumulate afterwards is the shared orthonormalizer branch (16.1)
    g0 = got[0]
    r0 = traj[start + 1]
    step_w = max(abs(g0[15 + i] - r0['omega'][i]) for i in range(3))
    step_r = max(max(abs(g0[3 + i] - r0['right'][i]) for i in range(3)),
                 max(abs(g0[6 + i] - r0['up'][i]) for i in range(3)),
                 max(abs(g0[9 + i] - r0['at'][i]) for i in range(3)))

    check("%s: %d frames, position tracks to %.2e m" % (label, window,
                                                        worst_p),
          worst_p < 1e-3)
    check("%s: %d frames, velocity tracks to %.2e m/s" % (label, window,
                                                          worst_v),
          worst_v < 1e-3)
    scale0 = max(1.0, max(abs(x) for x in r0['angmom']))
    step_L = max(abs(g0[18 + i] - r0['angmom'][i]) for i in range(3)) / scale0
    check("%s: angular momentum exact on the first crashed frame (%.2e)"
          % (label, step_L), step_L < 1e-5)
    # L is damped per world axis, so once the frames diverge L follows the
    # orientation residual; bound it by that budget rather than pretending
    check("%s: angular momentum tracks to %.2e (30 frames, relative)"
          % (label, worst_L), worst_L < max(1e-5, row_budget * 0.05))
    check("%s: omega exact on the first crashed frame (%.2e)"
          % (label, step_w), step_w < 1e-4)
    check("%s: per-step orientation residual %.2e (FUN_000FF270 branch)"
          % (label, step_r), step_r < 4e-3)
    check("%s: %d frames, orientation rows within %.3f" % (label, window,
                                                           worst_r),
          worst_r < row_budget,
          "budget %.3f -- accumulated orthonormalizer residual" % row_budget)
    return sim, speed, pre, traj


def seq_case(exe, label, seqfn, arm_impact, window=180, frames=300):
    """THE WHOLE-SEQUENCE DIFFERENTIAL.

    The three pieces (frame timer, crashed vehicle step, chase camera) are
    each verified in isolation elsewhere.  This asserts their COMPOSITION:
    the oracle runs one continuous session that, per RENDERED frame, ticks
    the real timer, steps the real crashed path at the dt that tick
    produced, and runs the real mode-2 camera on it.  The port is then
    driven with the SAME per-rendered-frame dt series and its
    apparent-rotation curve is diffed against the oracle's.
    """
    # the series is always long enough to contain the whole presentation
    # (the impact window alone is 15 + 126 rendered frames), so the branch
    # analysis below sees its real shape even under --quick, which only
    # shortens the frame-by-frame DIFF window.
    r = seqfn(frames=frames, arm_impact=arm_impact, camera=True)
    s = r['series']
    body = r['body']
    start = next((i for i, f in enumerate(s) if f['airborne']), 0)
    n = min(window, len(s) - start - 1)
    seed = s[start]
    st = {}
    rows = [seed['right'], seed['up'], seed['at'], seed['pos']]
    for row in range(4):
        for c in range(3):
            st['frame_%d_%d' % (row, c)] = rows[row][c]
        st['frame_%d_3' % row] = 1.0 if row == 3 else 0.0
    for i in range(3):
        st['vel_%d' % i] = seed['vel'][i]
        st['omega_%d' % i] = seed['omega'][i]
        st['angmom_%d' % i] = seed['angmom'][i]
        st['dir_%d' % i] = seed['dir'][i]
    st['vel_3'] = seed['speed']
    st['dir_3'] = seed['dir'][3]
    st['omega_3'] = st['angmom_3'] = 0.0
    for i in range(3):
        st['iinv_%d' % i] = body['iinv_%d' % i]
        for j in range(4):
            st['iw_%d_%d' % (i, j)] = seed['iinv_world'][i][j]
    st['mass'] = body['mass']
    st['com_height'] = body['com_height']
    for f in range(n):
        st['dt_%d' % f] = s[start + 1 + f]['dt']
    got = run_driver(exe, 'seq', st, extra=[n])

    worst_app = worst_pos = 0.0
    tot_real = tot_port = 0.0
    for f in range(n):
        real = s[start + 1 + f]
        g = got[f]
        worst_app = max(worst_app, abs(g[0] - real['apparent_rot']))
        worst_pos = max(worst_pos,
                        max(abs(g[1 + i] - real['pos'][i]) for i in range(3)))
        tot_real += real['apparent_rot']
        tot_port += g[0]
    check("%s: %d rendered frames, per-frame APPARENT rotation within "
          "%.2e rad (%.4f deg)" % (label, n, worst_app,
                                   math.degrees(worst_app)),
          worst_app < 2e-3)
    check("%s: total swept angle %.1f deg (port) vs %.1f deg (real)"
          % (label, math.degrees(tot_port), math.degrees(tot_real)),
          abs(tot_port - tot_real) < 0.05)
    check("%s: %d rendered frames, position tracks to %.2e m"
          % (label, n, worst_pos), worst_pos < 1e-3)
    return r


def run_sequence_cases(quick):
    """Section 8 -- the composition, and the two presentation branches."""
    print("\n8. THE WHOLE CRASH SEQUENCE, per RENDERED frame "
          "(real timer + real crashed step + real mode-2 camera):")
    exe = build_driver()
    if exe is None:
        return
    window = 60 if quick else 180
    for label, fn in (("wall 35 m/s", ect.seq_wall35),
                      ("car-vs-car fatal", ect.seq_slam)):
        plain = seq_case(exe, "%s, plain crash" % label, fn, False, window)
        # The armed branch's frame-by-frame window stops at the end of the
        # dilated phase (15 + 126 rendered frames).  Past it the shell runs
        # at dt = 1/60 with a fast multi-axis tumble, where the SHARED
        # b3_mat_orthonormalize takes the wrong FUN_000FF270 branch
        # (RE_NOTES 16.1, a src/burnout3_vehicle_sim.c hand-off item) and
        # the per-step orientation residual compounds.  That residual is
        # bounded by its own case in section 2; asserting it again here at
        # 180 frames would only re-measure someone else's open item.
        armed = seq_case(exe, "%s, big-hit armed" % label, fn, True,
                         min(window, 120))

        # --- the presentation branch, measured on the oracle --------------
        def stats(r):
            s = r['series']
            return (max(f['apparent_rot'] for f in s),
                    [f['divisor'] for f in s],
                    [f.get('cam_yaw', 0.0) for f in s],
                    [f.get('cam_pitch', 0.0) for f in s])
        p_peak, p_div, p_yaw, p_pitch = stats(plain)
        a_peak, a_div, a_yaw, a_pitch = stats(armed)

        check("%s: a plain crash holds divisor 5 for the whole flight"
              % label, set(p_div[1:]) == {5},
              "divisors seen: %s" % sorted(set(p_div[1:])))
        check("%s: the big-hit branch truncates to full speed" % label,
              a_div.count(6) == 126 and a_div[-1] == 1,
              "div6 frames %d, last %d" % (a_div.count(6), a_div[-1]))
        # THE HEADLINE: what the eye sees per rendered frame
        check("%s: plain crash tumbles at %.2f deg/frame peak (stately)"
              % (label, math.degrees(p_peak)), math.degrees(p_peak) < 3.0)
        # measured: 4.9x for the 35 m/s wall (14.5 rad/s of entry spin),
        # 2.0x for the car-vs-car fatal (8.2 rad/s)
        check("%s: the truncated branch peaks at %.2f deg/frame -- %.1fx "
              "faster" % (label, math.degrees(a_peak), a_peak / p_peak),
              a_peak > p_peak * 1.8)
        # THE CAMERA: n = floor(60*dt + 0.5) is 0 at divisor 5 and 6, so
        # every blend is 1 - x^0 = 0 and the angles HOLD (FUN_0015E550
        # @0x0015E5DC).  This is the recovered crash-camera behaviour.
        dil = [i for i, d in enumerate(p_div) if d != 1]
        yaw_sw = max(abs(p_yaw[i] - p_yaw[dil[0]]) for i in dil)
        pit_sw = max(abs(p_pitch[i] - p_pitch[dil[0]]) for i in dil)
        check("%s: the crash camera HOLDS its yaw through the dilated "
              "window (%.4f deg of drift)" % (label, yaw_sw), yaw_sw < 1e-3)
        check("%s: ... and its pitch (%.4f deg of drift)"
              % (label, pit_sw), pit_sw < 1e-3)
        # and the truncated branch is exactly where the camera starts to
        # swing -- the regression guard on the old always-armed harness
        a_dil = [i for i, d in enumerate(a_div) if d != 1]
        a_full = [i for i, d in enumerate(a_div) if d == 1 and i > a_dil[-1]]
        if a_full:
            sw = max(abs(a_yaw[i] - a_yaw[a_dil[-1]]) for i in a_full)
            check("%s: once truncated, the camera swings %.1f deg of yaw"
                  % (label, sw), sw > 20.0)


