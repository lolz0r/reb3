def run_latch_cases():
    print("\n-- 9. the per-slot crash latch (FUN_0010DD20 / LAB_0010E431)")
    data = open(os.path.join(_root, 'build', 'burnout3.elf'), 'rb').read()
    ph_off = struct.unpack_from('<I', data, 0x1C)[0]
    ph_num = struct.unpack_from('<H', data, 0x2C)[0]
    segs = [s for s in (struct.unpack_from('<IIIIIIII', data, ph_off + i * 32)
                        for i in range(ph_num)) if s[0] == 1]

    def rd(va, n):
        for _t, o, v, _p, f, _m, _fl, _a in segs:
            if v <= va < v + f:
                return data[o + (va - v):o + (va - v) + n]
        return b'\0' * n

    for name, va, n, want in LATCH_BYTES:
        got = rd(va, n)
        check(name, got == want, "got %s want %s" % (got.hex(), want.hex()))

    def rf(va):
        return struct.unpack('<f', rd(va, 4))[0]

    for name, va, want in (("[0x003B1708] truck fresh", 0x003B1708, 7.0),
                           ("[0x003B16B4] presented", 0x003B16B4, 15.0),
                           ("[0x003B1698] car fresh", 0x003B1698, 3.0),
                           ("[0x003B1C5C] car presented+17390", 0x003B1C5C,
                            17.0),
                           ("[0x003B1730] second timer", 0x003B1730, 0.25),
                           ("[0x003B16E0] the cooldown compare", 0x003B16E0,
                            0.0)):
        check(name + " = %g" % want, abs(rf(va) - want) < 1e-6,
              "got %g" % rf(va))

    # ...and the C port's table against those same immediates.
    exe = build_driver()
    if not exe:
        check("crash-latch driver builds", False)
        return
    got = run_driver(exe, 'latch', {})[0]
    for name, g, want in (("b3_crash_latch_duration(truck, fresh)", got[0],
                           7.0),
                          ("b3_crash_latch_duration(truck, presented)", got[1],
                           15.0),
                          ("b3_crash_latch_duration(car, fresh)", got[2], 3.0),
                          ("b3_crash_latch_duration(car, presented) [S: the "
                           "!FUN_00017390 arm]", got[3], 15.0)):
        check(name + " = %g" % want, abs(g - want) < 1e-6, "got %g" % g)


