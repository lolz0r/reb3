def pose_rows(yaw_deg, roll_deg):
    """Orthonormal frame: yaw about y then roll about the at axis."""
    cy, sy = math.cos(math.radians(yaw_deg)), math.sin(math.radians(yaw_deg))
    at = [sy, 0.0, cy]
    right0 = [cy, 0.0, -sy]
    up0 = [0.0, 1.0, 0.0]
    cr, sr = math.cos(math.radians(roll_deg)), math.sin(math.radians(roll_deg))
    right = [right0[i] * cr + up0[i] * sr for i in range(3)]
    up = [-right0[i] * sr + up0[i] * cr for i in range(3)]
    return right, up, at


def run_kick_cases():
    print("\n1. crash-entry kick (FUN_00125100 / FUN_00125380 differential):")
    exe = build_driver()
    if exe is None:
        check("build the C driver", False, "compilation failed")
        return
    sim = ect.CrashTraj(dt=DT)
    pos = [12.0, 3.5, -47.0]
    for (name, flags, mag, via, row, yaw, roll) in KICK_CASES:
        right, up, at = pose_rows(yaw, roll)
        rows = [right + [0.0], up + [0.0], at + [0.0], pos + [1.0]]
        for r in range(4):
            for c in range(4):
                sim.wf(CTX0 + 16 * r + 4 * c, rows[r][c])
        # clear the impulse accumulators and put the body to sleep so the
        # wake side effect (veh+0x20E := 0) is observable
        for off in range(0x110, 0x130, 4):
            sim.wf(VEHICLE + off, 0.0)
        sim.wb(VEHICLE + 0x20E, 1)
        if via:
            sim.kick_axis(flags, mag)
        else:
            sim.kick(flags, mag, CTX0 + 0x10 * row)
        real = ([sim.vf(0x110 + 4 * i) for i in range(3)]
                + [sim.vf(0x120 + 4 * i) for i in range(3)]
                + [sim.vb(0x20E)])
        st = {}
        for r in range(4):
            for c in range(4):
                st['frame_%d_%d' % (r, c)] = rows[r][c]
        for i in range(4):
            st['bbmax_%d' % i] = sim.vf(0x1D0 + 4 * i)
            st['bbmin_%d' % i] = sim.vf(0x1E0 + 4 * i)
        st['mass'] = sim.vf(0x1F0)
        st['flags'] = flags
        st['mag'] = mag
        st['via_axis'] = via
        st['axis_row'] = row
        got = run_driver(exe, 'kick', st)[0]
        bad = []
        for i, lbl in enumerate(('imp.x', 'imp.y', 'imp.z',
                                 'L.x', 'L.y', 'L.z')):
            tol = max(1e-3, abs(real[i]) * 2e-5)
            if abs(got[i] - real[i]) > tol:
                bad.append("%s %.6g != %.6g" % (lbl, got[i], real[i]))
        if int(got[6]) != int(real[6]):
            bad.append("asleep %d != %d" % (int(got[6]), int(real[6])))
        check(name, not bad, "; ".join(bad))


