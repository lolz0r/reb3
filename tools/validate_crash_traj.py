#!/usr/bin/env python3
"""
Acceptance test for the CRASH TRAJECTORY: the ported crash-entry kick and
crashed-path solver in src/burnout3_crash.c must reproduce the REAL retail
code running under Unicorn (tools/emulate_crash_traj.py).

Sections
  1. crash-entry kick        FUN_00125100 / FUN_00125380 whole-function
                             differential over a flag/pose/magnitude matrix
  2. crashed-path trajectory multi-frame 6DOF differential: seed the C port
                             from the real machine's state at the first fully
                             airborne frame and step it for the rest of the
                             wreck's flight; position, orientation rows,
                             velocity, omega and angular momentum must track
  3. flight assertions       the real wreck must LEAVE THE GROUND and rotate
                             through more than one axis (the behaviour the
                             module exists to reproduce)
  4. launch ablation         a torque-only entry does NOT launch; the pure
                             linear up-axis kick is what does.  This is the
                             regression guard on the actual bug.
  5. settle predicate        FUN_00125CF0 whole-function differential
  6. sleep gate              driven through the REAL FUN_00123000: every
                             condition of the 0x00123412..0x001235ED block,
                             one violated at a time
  7. scrape                  FUN_00123FD0 @0x001248EA composed from the REAL
                             callees (FUN_001066A0 / FUN_00011640 /
                             FUN_00013C60 / FUN_001115C0 / FUN_001064B0) vs
                             b3_crash_scrape
  8. AT REST                 the retail wreck comes to a dead stop and stays
                             there; the harness wreck must do the same --
                             land, settle, sleep, and not drift or climb,
                             with aftertouch held as well.  This is the
                             regression guard on "the wreck bobbles into
                             space".

Usage: python3 tools/validate_crash_traj.py [--quick]
"""
