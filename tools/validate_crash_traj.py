def _sleep_setup(sim, **over):
    """Put the real vehicle in the state the sleep block wants, then let the
    caller violate one condition at a time."""
    sim.wb(VEHICLE + 0x210, 1)            # crash mode
    # veh+0x211 must be 0: FUN_00109560 @0x00109592 clears the sleep byte
    # every step while it is set, so a body in that state never stays asleep
    sim.wb(VEHICLE + 0x211, over.get('state211', 0))
    sim.wb(VEHICLE + 0x20E, 0)            # awake
    sim.wb(VEHICLE + 0x116B, 0)
    sim.wb(VEHICLE + 0x1354, over.get('settle', 20))
    sim.wb(VEHICLE + 0x212, over.get('state212', 1))
    sim.wb(VEHICLE + OFF_CHASSIS_SURFACE, 0x01)
    # velocity / speed: the settle branch tests +0xBC
    speed = over.get('speed', 0.2)
    for i in range(3):
        sim.wf(VEHICLE + 0xB0 + 4 * i, 0.0)
    sim.wf(VEHICLE + 0xB0, speed)
    sim.wf(VEHICLE + 0xBC, speed)
    # angular momentum / omega
    w = over.get('omega', 0.1)
    for i in range(3):
        sim.wf(VEHICLE + 0xD0 + 4 * i, 0.0)
        sim.wf(VEHICLE + 0xE0 + 4 * i, 0.0)
    sim.wf(VEHICLE + 0xD0, w)
    # veh+0x170: the recorded contact axis, along the body up row
    for i in range(4):
        sim.wf(VEHICLE + 0x170 + 4 * i, 0.0)
    sim.wf(VEHICLE + 0x170 + 4, over.get('axis', 1.0))
    # the kick stamp the clock has to be past (0x00123564 compares the
    # global clock DAT_0060EA20 with ctx1+0xFFC)
    sim.wf(ect.ep.G_CLOCK, 10.0)
    sim.wf(CTX1 + 0xFFC, over.get('stamp', 0.0))
    # wheels: grounded on road so FUN_00125CF0's wheel arm is happy too
    ny = over.get('wheel_normal_y', 1.0)
    up_index = over.get('wheel_up_index', -1)
    for i in range(4):
        wc = 0 if i == up_index else over.get('wheel_contact', 1)
        sim.wb(VEHICLE + OFF_WHEEL_CONTACT + i * 0xC0, wc)
        sim.wb(VEHICLE + OFF_WHEEL_SURFACE + i * 0xC0, 0x01)
        sim.wb(CTX1 + OFF_WHEEL_DAMAGE + i, 0)
        # wheel+0x20 contact normal / wheel+0xB3 contact flag: the arm the
        # sleep gate uses when there is no chassis contact
        for j in range(4):
            sim.wf(VEHICLE + 0x840 + i * 0xC0 + 4 * j, 0.0)
        sim.wf(VEHICLE + 0x840 + i * 0xC0 + 4, ny)   # wheel+0x20 normal.y
        # (wheel+0x20 + 0x93 IS veh+0x8D3 + i*0xC0, already written above)


