def build_driver(defines=(), tag=''):
    src = os.path.join(_root, 'build', 'crash_traj_drv.c')
    exe = os.path.join(_root, 'build', 'crash_traj_drv' + tag)
    os.makedirs(os.path.join(_root, 'build'), exist_ok=True)
    with open(src, 'w') as f:
        f.write(DRIVER_C)
    r = subprocess.run(['cc', '-O2', '-Isrc'] + list(defines)
                       + ['-o', exe, src,
                          'src/burnout3_crash.c', 'src/burnout3_vehicle_sim.c',
                          '-lm'], cwd=_root, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stderr)
        return None
    return exe


def run_driver(exe, mode, state, extra=()):
    path = os.path.join(_root, 'build', 'crash_traj_state.txt')
    with open(path, 'w') as f:
        for k, v in state.items():
            f.write('%s %.9g\n' % (k, v))
    r = subprocess.run([exe, mode, path] + [str(e) for e in extra],
                       cwd=_root, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(r.stderr)
    return [[float(x) for x in line.split()]
            for line in r.stdout.strip().splitlines()]


