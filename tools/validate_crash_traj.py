def run_rest_cases(quick):
    print("\n8. at rest -- the REAL crashed path runs to quiescence:")
    frames = 400 if quick else 900
    sim = ect.CrashTraj(dt=DT)
    for _ in range(120):
        sim.frame(0.35, 0.0, 0.0, 0)
    pre = sim.capture6()
    # a gentle corner flick with no launch: the car stays on its wheels, so
    # the real machine's own suspension can bring it to rest
    sim.enter_crash(ect.KICK_REAR | ect.KICK_LEFT, 0.10, None)
    traj = [sim.crashed_frame() for _ in range(frames)]
    tail = traj[len(traj) // 2:]
    speeds = [math.sqrt(sum(v * v for v in t['vel'])) for t in tail]
    ys = [t['pos'][1] for t in tail]
    drift = max(ys) - min(ys)
    check("real wreck stops dead: |v| <= %.2e m/s over the last %d frames"
          % (max(speeds), len(tail)), max(speeds) < 1e-3)
    check("real wreck holds its height: %.2e m of drift" % drift,
          drift < 1e-3)
    # the settle counter is a BYTE and wraps -- it is never saturated
    counts = [t['settle'] for t in traj]
    check("settle counter runs and wraps as a byte (max %d, wraps %d)"
          % (max(counts), sum(1 for a, b in zip(counts, counts[1:])
                              if b < a)),
          max(counts) == 255 and any(b < a for a, b in zip(counts,
                                                           counts[1:])))
    # and it never sleeps, because FUN_0011BE50's crashed path never records
    # a chassis contact -- the gate at 0x00123414
    check("no chassis contact on the crashed path -> veh+0x20E stays 0",
          all(t['asleep'] == 0 for t in traj)
          and all(t['crashmode'] != 0 for t in traj))

    print("\n   the HARNESS wreck: launch, tumble, land, REST:")
    exe = build_driver()
    if exe is None:
        check("build the C driver", False, "compilation failed")
        return
    base = {
        'pos_0': 0.0, 'pos_1': 10.0, 'pos_2': 0.0,
        'vel_0': 0.0, 'vel_1': 0.0, 'vel_2': -32.0,
        'bbmin_0': -0.95, 'bbmin_1': -0.35, 'bbmin_2': -2.1,
        'bbmax_0': 0.95, 'bbmax_1': 1.15, 'bbmax_2': 2.1,
        'cp_0': 0.6, 'cp_1': 9.7, 'cp_2': -2.0,
        'cn_0': 0.0, 'cn_1': 0.0, 'cn_2': 1.0,
        'rv_0': 0.0, 'rv_1': 0.0, 'rv_2': -32.0,
        'heading': 0.0, 'mass': 1500.0,
        'corner': 0x0A, 'mag_spin': 0.40, 'mag_launch': 0.65,
        'iinv_0': 0.0008, 'iinv_1': 0.0011, 'iinv_2': 0.0013,
        'ground': 10.0, 'dt': DT, 'after_x': 0.0, 'after_z': 0.0,
        'after_frames': 0,
    }
    n = 600 if quick else 1200
    rows = run_driver(exe, 'wreck', base, extra=[n])
    ys = [r[1] for r in rows]
    peak = max(ys)
    launch_vy = rows[0][4]
    # the arc
    check("harness wreck launches (%.2f m/s up, peak %+.2f m over the road)"
          % (launch_vy, peak - base['ground']), launch_vy > 1.0
          and peak - base['ground'] > 1.0)
    upy = [r[11] for r in rows]
    check("stays right way up on frame 1 (up.y %+.3f -- the mirrored basis "
          "used to be flipped by the orthonormalizer)" % upy[0], upy[0] > 0.5)
    turned = sum(1 for u in upy if u < 0.5)
    check("tumbles (%d frames with the roof off vertical)" % turned,
          turned > 5)
    # the rest
    # driver columns: 0-2 pos, 3-6 vel(+speed), 7-9 omega, 10-12 up row,
    # 13 settle, 14 asleep, 15 airborne
    tail = rows[len(rows) * 3 // 4:]
    tail_y = [r[1] for r in tail]
    tail_sp = [r[6] for r in tail]
    tail_w = [math.sqrt(r[7] ** 2 + r[8] ** 2 + r[9] ** 2) for r in tail]
    drift = max(tail_y) - min(tail_y)
    horiz = max(abs(tail[-1][0] - tail[0][0]), abs(tail[-1][2] - tail[0][2]))
    check("comes to rest: %.4f m of height jitter over the last %d frames"
          % (drift, len(tail)), drift < 0.05)
    check("stays put: %.4f m of horizontal travel over the last %d frames"
          % (horiz, len(tail)), horiz < 0.15,
          "this shell ends on its SIDE, where the box has two contact "
          "corners and rocks; the upright case below is the tight one")
    # |v| under the settle gate's 1.0 (0x00123346) and the rocking of a
    # shell lying on its edge well under a rad/s -- it passed the sleep
    # gate's |w|^2 < 0.25 when it slept, below.
    check("under the retail settle limit: |v| %.3f < 1.0 (0x00123346), "
          "|w| %.3f rad/s" % (max(tail_sp), max(tail_w)),
          max(tail_sp) < 1.0 and max(tail_w) < 1.0)
    # a wreck that lands on its wheels is the case with the tight bounds:
    # it must sleep and stop dead
    up_rest = dict(base)
    up_rest['vel_2'] = -12.0
    up_rest['rv_2'] = -12.0
    up_rest['mag_spin'] = 0.10
    up_rest['mag_launch'] = 0.0
    rows_u = run_driver(exe, 'wreck', up_rest, extra=[n])
    tu = rows_u[len(rows_u) * 3 // 4:]
    ju = max(r[1] for r in tu) - min(r[1] for r in tu)
    hu = max(abs(tu[-1][0] - tu[0][0]), abs(tu[-1][2] - tu[0][2]))
    check("landing on its wheels: %.4f m of height jitter, %.4f m of travel, "
          "upright (up.y %+.3f)" % (ju, hu, tu[-1][11]),
          ju < 0.05 and hu < 0.01 and tu[-1][11] > 0.9)
    check("landing on its wheels: ASLEEP (veh+0x20E semantics) and it stays "
          "asleep", int(tu[-1][14]) == 1
          and all(int(r[14]) == 1 for r in tu))
    # THE bug: no upward creep once it is down
    landed = None
    for i, r in enumerate(rows):
        if i > 60 and int(r[15]) == 0 and abs(r[4]) < 0.5:
            landed = i
            break
    if landed is None:
        landed = len(rows) // 2
    climb = max(ys[landed:]) - ys[landed]
    check("never climbs after landing (%+.4f m from frame %d on)"
          % (climb, landed), climb < 0.05,
          "this is the 'bobbles into space' regression guard")

    # ... and with AFTERTOUCH HELD.  How high a wreck flies under a held
    # direction is not a free parameter: the retail shaper fires one 0.6
    # corner torque kick per frame with no cooldown, so the real machine
    # itself throws the shell metres into the air.  Measure that first and
    # hold the port to the same band.
    real_sim = ect.CrashTraj(dt=DT)
    for _ in range(120):
        real_sim.frame(0.35, 0.0, 0.0, 0)
    ry0 = real_sim.capture6()['pos'][1]
    real_sim.enter_crash(ect.KICK_REAR | ect.KICK_LEFT, 0.10, None)
    rt = []
    for _ in range(300):
        # FUN_00118410 @0x001181B4: flags 9, mag 0.6, axis = the up row
        real_sim.kick(0x09, 0.60, real_sim.frame_row(1))
        rt.append(real_sim.crashed_frame())
    real_peak = max(t['pos'][1] for t in rt) - ry0
    held = dict(base)
    held['after_x'] = 1.0
    rows2 = run_driver(exe, 'wreck', held, extra=[n])
    peak2 = max(r[1] for r in rows2) - base['ground']
    check("aftertouch held: the REAL machine throws the wreck %+.2f m up "
          "(one 0.6 corner kick per frame, no cooldown)" % real_peak,
          real_peak > 3.0)
    # The port must never EXCEED the real machine here -- that is the bug
    # class the user hit (+105 m/s of vy).  It sits under it because the
    # harness's flat-box contact is zero-restitution in the linear channel
    # (an impulse has no force bound, so it cannot be allowed to convert
    # angular momentum into com lift the way retail's spring/bottom-out pass
    # legitimately does).  RE_NOTES 16.2 records the deviation.
    check("aftertouch held: the port reaches %+.2f m -- responds, and stays "
          "under the real machine's %+.2f m" % (peak2, real_peak),
          1.0 < peak2 < real_peak)
    settles = [r[13] for r in rows2]
    check("aftertouch does not reset the settle counter (max %d) -- retail "
          "only clears it at speed >= 1 (0x001236E0)" % max(settles),
          max(settles) > 5)
    # release the input: the wreck must come back down and settle
    # (the shell is metres up when the input stops, so give it the airtime
    # back before looking at the tail)
    rel = dict(base)
    rel['after_x'] = 1.0
    rel['after_frames'] = n // 4
    rows3 = run_driver(exe, 'wreck', rel, extra=[n * 2])
    tail3 = rows3[len(rows3) * 3 // 4:]
    y3 = [r[1] for r in tail3]
    sp3 = [r[6] for r in tail3]
    check("aftertouch released: back on the ground and at rest "
          "(%.3f m of jitter, |v| <= %.3f over the last %d frames)"
          % (max(y3) - min(y3), max(sp3), len(tail3)),
          max(y3) - min(y3) < 0.05 and max(sp3) < 1.0)

    # ---- the CRASH SLOW-MO (the takedown FX divisor 5: the harness steps
    # the wreck once per RENDERED frame with sim dt/5) --------------------
    print("\n   under the crash slow-mo (sim dt / 5, 300 steps a second):")
    slow = dict(base)
    slow['dt'] = DT / 5.0
    rows4 = run_driver(exe, 'wreck', slow, extra=[n * 5])
    # the free-flight arc must be EXACTLY gravity, whatever the step size
    bad = 0
    for i in range(1, len(rows4)):
        if int(rows4[i][15]) == 1 and int(rows4[i - 1][15]) == 1:
            if abs((rows4[i][4] - rows4[i - 1][4]) + 20.0 * slow['dt']) > 1e-3:
                bad += 1
    check("no input: every airborne step is exactly -20*dt of vy "
          "(%d anomalies in %d frames)" % (bad, len(rows4)), bad == 0,
          "energy must not enter the flight when the step shrinks")
    tail4 = rows4[len(rows4) * 3 // 4:]
    y4 = [r[1] for r in tail4]
    check("no input: comes to rest all the same (%.4f m of jitter, "
          "asleep %d)" % (max(y4) - min(y4), int(tail4[-1][14])),
          max(y4) - min(y4) < 0.05 and int(tail4[-1][14]) == 1)
    # held aftertouch under slow-mo: the kick is an IMPULSE, so firing it per
    # rendered frame would put five times the torque per simulated second
    # into the shell and hold it up for ever.  b3_wreck_aftertouch spends
    # banked simulated time instead (B3_AFTERTOUCH_PERIOD).
    slow_at = dict(slow)
    slow_at['after_x'] = 1.0
    rows5 = run_driver(exe, 'wreck', slow_at, extra=[n * 5])
    ys5 = [r[1] for r in rows5]
    peak5 = max(ys5)
    pk5 = ys5.index(peak5)
    check("aftertouch held in slow-mo: climbs to %+.2f m then FALLS back to "
          "%+.2f m" % (peak5 - base['ground'],
                       min(ys5[pk5:]) - base['ground']),
          min(ys5[pk5:]) - base['ground'] < 2.0,
          "the wreck must come down again, not float")
    check("aftertouch held in slow-mo: peak %+.2f m stays in the same band "
          "as the 60 Hz peak %+.2f m" % (peak5 - base['ground'], peak2),
          peak5 - base['ground'] < 2.0 * peak2)
    # ablation: the same run with the cadence match compiled out
    exe_nc = build_driver(defines=['-DB3_AFTERTOUCH_PERIOD=0.0f'],
                          tag='_nocadence')
    if exe_nc:
        rows6 = run_driver(exe_nc, 'wreck', slow_at, extra=[n * 5])
        # column 16 is the number of kicks the module actually applied
        k5, k6 = rows5[-1][16], rows6[-1][16]
        secs = len(rows5) * slow['dt']
        check("ABLATION: %d kicks in %.1f s of sim time with the cadence "
              "match (%.0f/s, the retail tick rate) vs %d without (%.0f/s)"
              % (k5, secs, k5 / secs, k6, k6 / secs),
              k6 > 4.0 * k5 and abs(k5 / secs - 60.0) < 2.0,
              "this is the regression guard on the per-frame kick rate")

    # ---- the user's second repro: a kerb clip at 130 mph under the
    # divisor-5 slow-mo with input held.  The dump had the wreck at
    # vel.y = +105.7 m/s (the vertical cap in FUN_00109560 is 120) with
    # airborne=0 -- a contact turning angular momentum into com lift, frame
    # after frame.  Nothing the contact does may raise vy above the entry
    # kick, whatever the ground height under the shell is.
    print("\n   130 mph kerb clip, slow-mo, input held (the live repro):")
    for label, gnd in (("flat road", 10.0), ("kerb +0.5 m", 10.5),
                       ("kerb +1.5 m", 11.5)):
        kerb = dict(base)
        kerb['vel_2'] = -58.0            # 130 mph
        kerb['rv_2'] = -58.0
        kerb['dt'] = DT / 5.0
        kerb['after_x'] = 1.0
        kerb['ground'] = gnd
        rowsk = run_driver(exe, 'wreck', kerb, extra=[900])
        vy_max = max(r[4] for r in rowsk)
        launch = rowsk[0][4]
        check("%s: peak vy %+.2f m/s never beats the entry kick %+.2f m/s"
              % (label, vy_max, launch), vy_max <= launch + 0.01,
              "a zero-restitution contact must not launch the shell")
        check("%s: peak height %+.2f m over the road"
              % (label, max(r[1] for r in rowsk) - gnd),
              max(r[1] for r in rowsk) - gnd < 6.0)


