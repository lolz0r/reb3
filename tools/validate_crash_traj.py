def run_flight_cases(runs, quick):
    print("\n3. the wreck must LEAVE THE GROUND and tumble:")
    # min axes: the head-on wall entry uses corner flags 0x02 (rear only, the
    # FUN_0010DD20 0x0010E40F shape), so its torque is a pure end-over-end
    # pitch -- one axis is CORRECT there.  The car-vs-car entry uses a real
    # corner (0x0A rear-left, 0x00024F94) and must tumble on two.
    for label, key, min_axes in (("car-vs-car fatal slam", 'slam', 2),
                                 ("40 m/s head-on wall", 'wall', 1)):
        sim, speed, pre, traj = runs[key]
        y0 = pre['pos'][1]
        rise = max(t['pos'][1] for t in traj) - y0
        vy0 = traj[0]['vel'][1]
        air = sum(1 for t in traj if t['airborne'])
        # rotation accumulated about each world axis
        rot = [0.0, 0.0, 0.0]
        for t in traj[:120]:
            for i in range(3):
                rot[i] += abs(t['omega'][i]) * DT
        axes = sum(1 for r in rot if r > 1.0)
        turns = math.sqrt(sum(r * r for r in rot)) / (2 * math.pi)
        check("%s: launch velocity %.2f m/s upward" % (label, vy0),
              vy0 > 4.0, "expected the pure-linear up kick (10 * mag)")
        check("%s: rises %.2f m off the ground" % (label, rise),
              rise > 1.0, "the wreck never leaves the ground")
        check("%s: %d/%d frames with no wheel on the ground"
              % (label, air, len(traj)), air > len(traj) // 4)
        check("%s: rotates through %d axes (%.1f, %.1f, %.1f rad)"
              % (label, axes, rot[0], rot[1], rot[2]), axes >= min_axes,
              "expected at least %d rotating axes" % min_axes)
        check("%s: turns over %.2f times in 2 s" % (label, turns),
              turns > 1.0, "a wreck that does not rotate is a slide")

    print("\n4. launch ablation (the regression guard on the actual bug):")
    sim, speed, pre, traj = ect.SCENARIOS['spin_only'](
        dt=DT, frames=90 if quick else 150)
    y0 = pre['pos'][1]
    vy0 = traj[0]['vel'][1]
    rise_spin = max(t['pos'][1] for t in traj) - y0
    check("torque-only entry: no launch velocity (%.2f m/s)" % vy0,
          vy0 < 1.0,
          "the corner torque alone must not produce upward velocity")
    _, _, pre2, traj2 = runs['slam']
    rise_full = max(t['pos'][1] for t in traj2) - pre2['pos'][1]
    check("linear kick adds %.2f m of height (%.2f -> %.2f)"
          % (rise_full - rise_spin, rise_spin, rise_full),
          rise_full > rise_spin + 0.4,
          "the pure-linear up-axis kick is the launch")


