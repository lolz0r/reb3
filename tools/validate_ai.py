class Probe(object):
    """Persistent process running the compiled src/burnout3_ai.c."""

    def __init__(self):
        os.makedirs(BUILD, exist_ok=True)
        with open(PROBE_C, "w") as fh:
            fh.write(PROBE_SRC)
        cc = subprocess.run(
            ["gcc", "-O1", "-std=c99", "-Wall", "-Wextra", "-Wno-unused-parameter",
             "-o", PROBE, PROBE_C, "-lm"],
            cwd=BUILD, capture_output=True, text=True)
        if cc.returncode:
            print(cc.stdout)
            print(cc.stderr)
            raise SystemExit("ai_probe failed to compile")
        self.warn = cc.stderr
        self.p = subprocess.Popen([PROBE], stdin=subprocess.PIPE,
                                  stdout=subprocess.PIPE, text=True,
                                  bufsize=1)

    def cmd(self, op, **kw):
        parts = [op]
        for k, v in kw.items():
            k = k.replace("__", ".")
            parts.append("%s=%s" % (k, ("%d" % v) if isinstance(v, int)
                                    else ("%.9g" % v)))
        self.p.stdin.write(" ".join(parts) + "\n")
        self.p.stdin.flush()
        line = self.p.stdout.readline()
        out = {}
        for kv in line.split():
            k, v = kv.split("=", 1)
            out[k] = float(v)
        return out

    def cmd_kv(self, op, kv):
        """Same as cmd() but takes a dict, so keys may contain dots."""
        parts = [op]
        for k, v in kv.items():
            parts.append("%s=%s" % (k, ("%d" % v) if isinstance(v, int)
                                    else ("%.9g" % v)))
        self.p.stdin.write(" ".join(parts) + "\n")
        self.p.stdin.flush()
        line = self.p.stdout.readline()
        out = {}
        for x in line.split():
            k, v = x.split("=", 1)
            out[k] = float(v)
        return out

    def reset(self):
        self.p.stdin.write("reset\n")
        self.p.stdin.flush()


