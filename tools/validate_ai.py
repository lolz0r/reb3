def set_agg(s, i, **kw):
    """Poke the retail aggression object directly (state seeding)."""
    a = s.agg(i)
    for k, v in kw.items():
        off = {"state": 0x00, "aim_valid": 0x20, "attacking": 0x21,
               "slam_speed": 0x22, "blocked": 0x23, "hit": 0x24,
               "timer": 0x2C, "entered": 0x30, "side": 0x34,
               "lateral": 0x38, "longitudinal": 0x3C, "can_slam": 0x40,
               "block_range": 0x41, "want_slam_speed": 0x42}[k]
        if k in ("state",):
            s.wi(a + off, v)
        elif k in ("aim_valid", "attacking", "slam_speed", "blocked", "hit",
                   "can_slam", "block_range", "want_slam_speed"):
            s.wb(a + off, v)
        else:
            s.wf(a + off, v)


