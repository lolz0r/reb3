    got = p.cmd_kv("offworld", {"ownode": 11, "owdy": 0.5})
    fails += check("dy > -1 latches the last valid node",
                   [("fired", 0.0, got["owfired"]),
                    ("below", 0.0, got["below"]),
                    ("lastnode", 11.0, got["lastnode"])])

    # 2. the -1..-5 band clears the counter
    p.reset()
    p.cmd("winit", ownode=0)
    p.cmd_kv("offworld", {"ownode": 5, "owdy": -6.0})
    got = p.cmd_kv("offworld", {"ownode": 5, "owdy": -3.0})
    fails += check("dy in (-5,-1) clears the counter",
                   [("fired", 0.0, got["owfired"]),
                    ("below", 0.0, got["below"])])

    # 3. the 61-frame drop
    p.reset()
    p.cmd("winit", ownode=0)
    fired_at = -1
    for i in range(1, 200):
        got = p.cmd_kv("offworld", {"ownode": 5, "owdy": -6.0})
        if got["owfired"]:
            fired_at = i
            break
    fails += check("dy < -5 fires on frame 61 (0x3D)",
                   [("frame", 61.0, float(fired_at)),
                    ("counter cleared", 0.0, got["below"])])

    # 4. the 200-frame nav-walk-failure rescue
    p.reset()
    p.cmd("winit", ownode=0)
    fired_at = -1
    for i in range(1, 400):
        got = p.cmd_kv("navfail", {"walkok": 0})
        if got["navfired"]:
            fired_at = i
            break
    fails += check("nav-walk failure fires at 201 (> 0xC8)",
                   [("frame", 201.0, float(fired_at)),
                    ("counter cleared", 0.0, got["navfail"])])

    # 5. retail does NOT clear it on a good frame (only the rescue does)
    p.reset()
    p.cmd("winit", ownode=0)
    p.cmd_kv("navfail", {"walkok": 0})
    p.cmd_kv("navfail", {"walkok": 0})
    got = p.cmd_kv("navfail", {"walkok": 1})
    fails += check("a good walk does not reset the counter",
                   [("counter", 2.0, got["navfail"])])

    # 6. the skip-once latch (FUN_00171650 -> FUN_00170820 @0x001708C7)
    p.reset()
    got = p.cmd("winit", ownode=3)
    fails += check("the re-placer's skip latch starts clear",
                   [("skip", 0.0, got["skip"]),
                    ("route alt starts at 1", 1.0, got["alt"])])
    return fails


