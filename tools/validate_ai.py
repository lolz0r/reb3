def run_multiframe():
    """Drive the REAL FUN_00171E30 and the C for 60 consecutive frames over a
    swept aim direction, carrying the slew state on both sides."""
    print("\nmulti-frame trajectory (60 frames, swept aim direction):")
    s = ea.Session()
    ea.seed_car(s, speed=45.0)
    s.wb(VEH + 0x1550, 0)
    s.wf(AI + 0x9C8, 1.0)
    s.wf(AI + 0x9CC, 0.0)
    p = probe()
    p.reset()
    p.cmd("angle", speed=45.0, lsdm=0, t2ts=1.0, prevang=0.0,
          fwd__x=0.0, fwd__y=0.0, fwd__z=1.0,
          right__x=1.0, right__y=0.0, right__z=0.0,
          carat__x=0.0, carat__y=0.0, carat__z=1.0,
          ddn__x=0.0, ddn__y=0.0, ddn__z=1.0)
    p.cmd("angle", prevang=0.0)          # reset the limiter memory
    worst = 0.0
    worst_f = -1
    for f in range(60):
        # aim sweeps right then back left: a corner entry and exit
        th = math.radians(70.0 * math.sin(f * math.pi / 30.0))
        dd = [math.sin(th), 0.0, math.cos(th)]
        s.wv(AI + 0x7B0, dd + [0.0])
        s.call(ea.F_TARGET_ANGLE, regs={UC_X86_REG_ESI: AI})
        real = s.rf(AI + 0x9C0)
        got = p.cmd("angle", ddn__x=dd[0], ddn__y=dd[1], ddn__z=dd[2])
        d = abs(real - got["tang"])
        if d > worst:
            worst, worst_f = d, f
    ok = worst < 1e-4
    print("  %-42s %s" % ("60-frame swept aim, slew carried",
                          "OK  (worst |delta| %.3e @ frame %d)"
                          % (worst, worst_f) if ok else
                          "FAIL worst %.4g @ frame %d" % (worst, worst_f)))
    if s.fault:
        print("      (emulation fault: %s)" % s.fault)
        return 1
    return 0 if ok else 1


