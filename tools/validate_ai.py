# 12. A whole attack CYCLE, frame by frame, with the state carried on both
#     sides: idle -> approach -> steer out -> slam -> contact -> recoil ->
#     cooldown -> idle.  240 frames at 60 Hz.
# ===========================================================================
def run_aggro_cycle():
    print("\nAggression 240-frame cycle (state carried on both sides):")
    p = probe()
    clock0 = 20.0
    dt = 1.0 / 60.0
    scn = _pair(6.0, 2.0, b=dict(track=102.0, speed=44.0))
    s, kv = seed_pair(dict(scn, clock=clock0, dt=dt))
    s.agg_init(0)
    set_agg(s, 0, state=0, timer=-1.0)
    p.reset()
    p.cmd_kv("agginit", kv)
    pk = dict(kv)
    pk["a.state"] = 0
    pk["a.timer"] = -1.0
    worst = 0.0
    bad = []
    lat = 6.0
    for f in range(240):
        clk = clock0 + f * dt
        # close in laterally, then bump at frame 120
        if f > 20 and lat > 1.0:
            lat -= 0.05
        hit = 1 if f == 120 else 0
        for i in (0, 1):
            s.wf(s.rc(i) + 0x10DC, clk)
        s.wf(ea.G_CLOCK, clk)
        s.place(1, (lat, 0.0, 2.0), speed=44.0, track=102.0)
        s.wf(s.rc(0) + 0x18A4 + 1 * 4, lat)
        s.wb(s.agg(0) + 0x24, hit)
        s.call(ea.F_AGG_UPDATE, regs={UC_X86_REG_EAX: s.agg(0)})
        if s.fault:
            bad.append("frame %d unicorn %s" % (f, s.fault))
            break
        real = agg_real(s, 0, kv)
        pk = dict(kv)
        pk["clk"] = clk
        pk["c0.race_time"] = clk
        pk["c1.race_time"] = clk
        pk["c1.pos.x"] = lat
        pk["c0.lat1"] = lat
        pk["a.hit"] = hit
        if f == 0:                       # carry the same initial seed
            pk["a.state"] = 0
            pk["a.timer"] = -1.0
        got = p.cmd_kv("aggupd", pk)
        # the module keeps its own state; only the scenario is re-fed
        for k in AGG_KEYS:
            d = abs(float(real[k]) - got[k])
            if d > worst:
                worst = d
            if d > 1e-4:
                bad.append("frame %d %s %.7g != %.7g"
                           % (f, k, got[k], float(real[k])))
        if bad:
            break
    print("  %-42s %s" % ("240-frame attack cycle (worst |delta| %.3g)" % worst,
                          "OK" if not bad else "FAIL " + "; ".join(bad[:3])))
    return 1 if bad else 0


