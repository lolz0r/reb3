def check(name, pairs, tol=TOL):
    """pairs: list of (label, real, mine).  Returns 0 on success."""
    bad = []
    for label, real, mine in pairs:
        if real != real or mine != mine:          # NaN
            bad.append("%s NaN (real %r mine %r)" % (label, real, mine))
        elif abs(real - mine) > tol * max(1.0, abs(real)):
            bad.append("%s %.7g != %.7g" % (label, mine, real))
    print("  %-42s %s" % (name, "OK" if not bad else "FAIL " + "; ".join(bad)))
    return 1 if bad else 0


def norm(v):
    n = math.sqrt(sum(x * x for x in v[:3]))
    return [x / n for x in v[:3]]


